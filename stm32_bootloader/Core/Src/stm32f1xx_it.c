/**
  * @brief This function handles USART2 global interrupt.
  */
void USART2_IRQHandler(void)
{
  /* USER CODE BEGIN USART2_IRQn 0 */
  /* ---- OTA 帧接收：IDLE 空闲中断 = 一帧结束 ----
   * 注意 1：必须在 HAL_UART_IRQHandler() 之前处理 IDLE，
   *         HAL 自己处理时会 ATOMIC_CLEAR_BIT(CR1, IDLEIE) 关掉空闲中断使能，
   *         导致后续再也收不到 IDLE —— 这正是"传几包就断"的根因之一。
   * 注意 2：IDLE 处理完必须直接 return，不能再进 HAL_UART_IRQHandler，
   *         因为此时 DMA 已停、HAL 会误判 RxState 并走去回调路径。
   */
  if (__HAL_UART_GET_FLAG(&huart2, UART_FLAG_IDLE) != RESET) {
      __HAL_UART_CLEAR_IDLEFLAG(&huart2);

      if (!OtaRxReady) {
          /* DMA 剩余计数 → 本帧真实长度 = 缓冲区总长 - 剩余 */
          uint16_t remain = (uint16_t)__HAL_DMA_GET_COUNTER(huart2.hdmarx);
          uint16_t len    = (uint16_t)(OTA_RX_BUF_SIZE - remain);
          if (len > 0 && len <= OTA_RX_BUF_SIZE) {
              OtaRxLen   = len;
              OtaRxReady = 1;
          }
      }
      /* 先停 DMA：让主循环处理完这帧后再由 OTA_RxStart() 重启，
       * 避免解析期间新数据覆盖接收缓冲区。                  */
      (void)HAL_UART_DMAStop(&huart2);

      /* 顺手清掉可能残留的错误标志（ORE/NE/FE/PE） */
      __HAL_UART_CLEAR_OREFLAG(&huart2);

      return;   /* IDLE 已处理完，不再进 HAL 分发 */
  }
  /* USER CODE END USART2_IRQn 0 */
  HAL_UART_IRQHandler(&huart2);
  /* USER CODE BEGIN USART2_IRQn 1 */

  /* USER CODE END USART2_IRQn 1 */
}

